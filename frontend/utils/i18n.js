function lookupWordWithStemmer(cleanTok) {
  const lowerTr = cleanTok.toLocaleLowerCase("tr-TR");
  if (DO_NOT_STEM_WORDS.has(lowerTr)) return null;
  if (WORD_DICT_TR_EN[lowerTr]) return WORD_DICT_TR_EN[lowerTr];
  const nk = normTrKey(cleanTok);
  if (DO_NOT_STEM_WORDS.has(nk)) return null;
  if (NORM_WORD_DICT_TR_EN[nk]) return NORM_WORD_DICT_TR_EN[nk];

  for (let i = 0; i < TR_SUFFIXES_NORM.length; i++) {
    const suf = TR_SUFFIXES_NORM[i];
    if (nk.length >= suf.length + 3 && nk.endsWith(suf)) {
      const stem = nk.slice(0, -suf.length);
      if (NORM_WORD_DICT_TR_EN[stem]) return NORM_WORD_DICT_TR_EN[stem];
      if (stem.endsWith("ğ") && NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "k"]) {
        return NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "k"];
      }
      if (stem.endsWith("d") && NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "t"]) {
        return NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "t"];
      }
      if (stem.endsWith("b") && NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "p"]) {
        return NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "p"];
      }
      if (stem.endsWith("c") && NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "ç"]) {
        return NORM_WORD_DICT_TR_EN[stem.slice(0, -1) + "ç"];
      }
    }
  }
  return null;
}

